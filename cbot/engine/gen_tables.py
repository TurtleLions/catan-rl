"""Write tables.h: the base map's fixed topology and the action numbering,
taken from Catanatron so the native engine (cbot/engine) numbers nodes,
edges, tiles, ports and moves exactly as it does.

    python -m cbot.engine.gen_tables

Only resources, numbers and port types vary between games; node and edge ids
depend on the topology alone.
"""

import os

from catanatron.models.board import STATIC_GRAPH, get_edges
from catanatron.models.enums import RESOURCES, ActionType, NodeRef
from catanatron.models.map import BASE_MAP_TEMPLATE, CatanMap, PORT_DIRECTION_TO_NODEREFS
from catanatron.models.spiral import spiral_land_coordinates
from catanatron.models.tiles import Port

from cbot import policy

NODEREFS = [NodeRef.NORTH, NodeRef.NORTHEAST, NodeRef.SOUTHEAST, NodeRef.SOUTH, NodeRef.SOUTHWEST, NodeRef.NORTHWEST]
# Native action types (cbot/engine/catan.h, enum Act).
TYPES = ["ROLL", "DISCARD_RESOURCE", "BUILD_ROAD", "BUILD_SETTLEMENT", "BUILD_CITY", "BUY_DEVELOPMENT_CARD",
         "PLAY_KNIGHT_CARD", "PLAY_YEAR_OF_PLENTY", "PLAY_ROAD_BUILDING", "PLAY_MONOPOLY", "MOVE_ROBBER",
         "MARITIME_TRADE", "END_TURN"]


def arr(name, ctype, rows):
    if rows and isinstance(rows[0], (list, tuple)):
        body = ",\n  ".join("{" + ", ".join(str(x) for x in r) + "}" for r in rows)
        return f"static const {ctype} {name}[{len(rows)}][{len(rows[0])}] = {{\n  {body}}};\n"
    return f"static const {ctype} {name}[{len(rows)}] = {{{', '.join(str(x) for x in rows)}}};\n"


def main():
    m = CatanMap.from_template(BASE_MAP_TEMPLATE)
    land = list(m.land_tiles.items())  # tile id order
    assert [t.id for _, t in land] == list(range(19))
    coord_id = {c: t.id for c, t in land}
    ports = sorted((t for t in m.tiles.values() if isinstance(t, Port)), key=lambda p: p.id)
    edges = get_edges()
    edge_id = {e: i for i, e in enumerate(edges)}
    assert all(a < b for a, b in edges)

    # STATIC_GRAPH also holds the water tiles' outer nodes (54+), where nothing
    # can be built; they never affect a rule, so only land neighbors are kept
    # (in Catanatron's adjacency order).
    nbr = [[v for v in STATIC_GRAPH.neighbors(n) if v < 54] for n in range(54)]
    nbr = [ns + [-1] * (3 - len(ns)) for ns in nbr]
    node_tiles = [[t.id for t in m.adjacent_tiles[n]] for n in range(54)]
    spiral = [coord_id[c] for c in spiral_land_coordinates(m.tiles, (2, -2, 0))]

    acts = []
    for t, v in policy._ARRAY:
        name = t.name
        x = y = z = -1
        if t == ActionType.DISCARD_RESOURCE or t == ActionType.PLAY_MONOPOLY:
            x = RESOURCES.index(v)
        elif t == ActionType.BUILD_ROAD:
            x = edge_id[v]
        elif t in (ActionType.BUILD_SETTLEMENT, ActionType.BUILD_CITY):
            x = v
        elif t == ActionType.PLAY_YEAR_OF_PLENTY:
            x = RESOURCES.index(v[0])
            y = RESOURCES.index(v[1]) if len(v) > 1 else -1
        elif t == ActionType.MOVE_ROBBER:
            x, y = coord_id[v[0]], int(v[1] is not None)
        elif t == ActionType.MARITIME_TRADE:
            give = [r for r in v[:4] if r is not None]
            x, y, z = RESOURCES.index(give[0]), RESOURCES.index(v[4]), len(give)
        acts.append((TYPES.index(name), x, y, z))
    # cbot.policy numbers a steal from "the opponent", which in 1v1 is the next
    # seat (y = 1). With more players the victim is a seat after the mover:
    # steals from the second and third seat after it are appended, so the 1v1
    # numbers stay as they are.
    n1v1 = len(acts)
    for rel in (2, 3):
        for t in range(19):
            acts.append((TYPES.index("MOVE_ROBBER"), t, rel, -1))

    out = ["// Generated by cbot/engine/gen_tables.py from Catanatron's base map. Do not edit.\n#pragma once\n"]
    out.append(arr("NODE_NBR", "int", nbr))
    out.append(arr("EDGE_NODES", "int", [list(e) for e in edges]))
    out.append(arr("TILE_NODES", "int", [[t.nodes[r] for r in NODEREFS] for _, t in land]))
    out.append(arr("NODE_TILES", "int", [ts + [-1] * (3 - len(ts)) for ts in node_tiles]))
    out.append(arr("PORT_NODES", "int", [[p.nodes[r] for r in PORT_DIRECTION_TO_NODEREFS[p.direction]] for p in ports]))
    out.append(arr("SPIRAL", "int", spiral))
    out.append(arr("ACTIONS", "int", acts))
    out.append(f"static const int NUM_ACTIONS = {len(acts)};\n")
    out.append(f"static const int NUM_ACTIONS_1V1 = {n1v1};  // cbot.policy.SIZE\n")
    path = os.path.join(os.path.dirname(__file__), "tables.h")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {path}: {len(acts)} actions, {len(edges)} edges")


if __name__ == "__main__":
    main()
